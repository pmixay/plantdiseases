/**
 * Drives the Aqua model sync (manifest GET → streaming model GET → install)
 * against a real [MockWebServer] through the migrated Ktor path. Needs a
 * Robolectric [Context] because [AquaModelManager.install] writes the model +
 * classes sidecar to `filesDir` and records the installed sha in prefs.
 *
 * Verifies two migration-specific things: the manifest's `classes` field
 * (Gson [com.google.gson.JsonObject], read via GsonJsonObjectSerializer)
 * survives the kotlinx round-trip into the sidecar, and model bytes are
 * consumed via `bodyAsChannel().toInputStream()`.
 */
@RunWith(RobolectricTestRunner::class)
@Config(sdk = [33])
class AquaSyncNetworkTest {

    private lateinit var server: MockWebServer
    private lateinit var repo: ScanRepository
    private lateinit var context: Context

    @Before
    fun setup() {
        server = MockWebServer()
        server.start()
        context = ApplicationProvider.getApplicationContext()
        clearInstalledAqua()
        repo = ScanRepository(FakeScanDao(), PlantApiClient(server.url("/").toString()))
    }

    @After
    fun teardown() {
        server.shutdown()
        clearInstalledAqua()
    }

    @Test
    fun syncAquaModel_downloadsAndInstalls_whenManifestFresh() {
        val modelBytes = tfliteContractBytes()
        val modelSha = MessageDigest.getInstance("SHA-256")
            .digest(modelBytes)
            .joinToString("") { "%02x".format(it) }
        val semanticClasses = """
            {
              "model_version": "7",
              "model_family": "aqua",
              "class_names": ["healthy", "leaf_spot"],
              "training": {"img_size": 224, "eval_resize_ratio": 1.05},
              "inference": {
                "layout": "NHWC",
                "tta": "none",
                "output_semantics": "logits",
                "normalize_mean": [0.485, 0.456, 0.406],
                "normalize_std": [0.229, 0.224, 0.225]
              }
            }
        """.trimIndent()
        val classesSha = MessageDigest.getInstance("SHA-256")
            .digest(canonicalJson(JsonParser.parseString(semanticClasses)).toByteArray(Charsets.UTF_8))
            .joinToString("") { "%02x".format(it) }
        // Fixed vector generated by server._aqua_classes_sha256 for this
        // semantic object; catches cross-language canonicalisation drift.
        assertThat(classesSha).isEqualTo(
            "be570eab1fa8836106596f08f5c16b8790e2119db6de77dc0e76ba834d5bfa87",
        )
        val bundleDigest = MessageDigest.getInstance("SHA-256").apply {
            update("plantvision-aqua-bundle-v1\u0000".toByteArray(Charsets.UTF_8))
            update(hexBytes(modelSha))
            update(hexBytes(classesSha))
        }
        val bundleSha = bundleDigest.digest().joinToString("") { "%02x".format(it) }

        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    """
                    {
                      "available": true,
                      "version": "7",
                      "sha256": "$modelSha",
                      "classes_sha256": "$classesSha",
                      "bundle_sha256": "$bundleSha",
                      "bundle_schema_version": 1,
                      "size_bytes": ${modelBytes.size},
                      "classes": $semanticClasses
                    }
                    """.trimIndent(),
                ),
        )
        // Model bytes streamed back as an octet-stream body.
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(modelBytes)),
        )

        val result = runBlocking { repo.syncAquaModel(context) }

        assertThat(result.isSuccess).isTrue()
        assertThat(result.getOrNull()).isTrue() // a new model was installed
        assertThat(AquaModelManager.isUpToDate(context, bundleSha)).isTrue()
        val installedMeta = JSONObject(AquaModelManager.classesFile(context).readText())
        assertThat(installedMeta.getString("_model_sha256")).isEqualTo(modelSha)
        assertThat(installedMeta.getString("_classes_sha256")).isEqualTo(classesSha)
        assertThat(installedMeta.getString("_bundle_sha256")).isEqualTo(bundleSha)
        assertThat(installedMeta.getString("_model_version")).isEqualTo("7")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/model")

        // Same model bytes, different serving sidecar: model-SHA freshness
        // would miss this update, while the combined bundle digest must fetch
        // and atomically replace it.
        val semanticClassesV2 = semanticClasses
            .replace("\"model_version\": \"7\"", "\"model_version\": \"8\"")
            .replace("\"eval_resize_ratio\": 1.05", "\"eval_resize_ratio\": 1.1")
        val classesShaV2 = classesSha256(semanticClassesV2)
        val bundleShaV2 = bundleSha256(modelSha, classesShaV2)
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    manifestBody(
                        version = "8",
                        modelSha = modelSha,
                        classesSha = classesShaV2,
                        bundleSha = bundleShaV2,
                        semanticClasses = semanticClassesV2,
                        sizeBytes = modelBytes.size,
                    ),
                ),
        )
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(modelBytes)),
        )

        val sidecarOnlyUpdate = runBlocking { repo.syncAquaModel(context) }

        assertThat(sidecarOnlyUpdate.getOrNull()).isTrue()
        assertThat(AquaModelManager.isUpToDate(context, bundleShaV2)).isTrue()
        assertThat(AquaModelManager.isUpToDate(context, bundleSha)).isFalse()
        val updatedMeta = JSONObject(AquaModelManager.classesFile(context).readText())
        assertThat(updatedMeta.getString("_model_sha256")).isEqualTo(modelSha)
        assertThat(updatedMeta.getString("_classes_sha256")).isEqualTo(classesShaV2)
        assertThat(updatedMeta.getString("_bundle_sha256")).isEqualTo(bundleShaV2)
        assertThat(updatedMeta.getString("_model_version")).isEqualTo("8")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/model")
    }

    @Test
    fun syncAquaModel_noop_whenManifestUnavailable() {
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody("""{"available":false}"""),
        )
        val result = runBlocking { repo.syncAquaModel(context) }
        assertThat(result.isSuccess).isTrue()
        assertThat(result.getOrNull()).isFalse() // nothing to install
    }

    @Test
    fun syncAquaModel_noop_whenManifestIsNotBundleBound() {
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    """{"available":true,"version":"legacy","sha256":"${"0".repeat(64)},"classes":{}}""",
                ),
        )

        val result = runBlocking { repo.syncAquaModel(context) }

        assertThat(result.isSuccess).isTrue()
        assertThat(result.getOrNull()).isFalse()
        assertThat(server.requestCount).isEqualTo(1) // manifest only; no model download
    }

    @Test
    fun syncAquaModel_rejectsMismatchedBundleDigest() {
        val modelBytes = ByteArray(512) { (it % 251).toByte() }
        val modelSha = sha256(modelBytes)
        val semanticClasses = """
            {
              "model_version": "9",
              "model_family": "aqua",
              "class_names": ["healthy", "leaf_spot"],
              "training": {"img_size": 224, "eval_resize_ratio": 1.05},
              "inference": {
                "layout": "NHWC", "tta": "none", "output_semantics": "logits",
                "normalize_mean": [0.485, 0.456, 0.406],
                "normalize_std": [0.229, 0.224, 0.225]
              }
            }
        """.trimIndent()
        val classesSha = classesSha256(semanticClasses)
        val wrongBundleSha = "f".repeat(64)
        assertThat(wrongBundleSha).isNotEqualTo(bundleSha256(modelSha, classesSha))
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    manifestBody(
                        version = "9",
                        modelSha = modelSha,
                        classesSha = classesSha,
                        bundleSha = wrongBundleSha,
                        semanticClasses = semanticClasses,
                        sizeBytes = modelBytes.size,
                    ),
                ),
        )
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(modelBytes)),
        )

        val result = runBlocking { repo.syncAquaModel(context) }

        assertThat(result.isSuccess).isTrue()
        assertThat(result.getOrNull()).isFalse()
        assertThat(AquaModelManager.isUpToDate(context, wrongBundleSha)).isFalse()
        assertThat(AquaModelManager.isInstalled(context)).isFalse()
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/model")

        // Install a valid two-class bundle so the rejection paths below have
        // an active last-known-good pointer to preserve.
        val validBytes = tfliteContractBytes()
        val validModelSha = sha256(validBytes)
        val semanticClassesV2 = semanticClasses
            .replace("\"model_version\": \"9\"", "\"model_version\": \"8\"")
        val classesShaV2 = classesSha256(semanticClassesV2)
        val bundleShaV2 = bundleSha256(validModelSha, classesShaV2)
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    manifestBody(
                        version = "8",
                        modelSha = validModelSha,
                        classesSha = classesShaV2,
                        bundleSha = bundleShaV2,
                        semanticClasses = semanticClassesV2,
                        sizeBytes = validBytes.size,
                    ),
                ),
        )
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(validBytes)),
        )
        val validInstall = runBlocking { repo.syncAquaModel(context) }
        assertThat(validInstall.getOrNull()).isTrue()
        assertThat(AquaModelManager.isUpToDate(context, bundleShaV2)).isTrue()
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/model")

        // A hash-valid replacement with a head for three classes must not
        // displace the currently active two-class bundle.
        val wrongHeadBytes = tfliteContractBytes(outputShape = intArrayOf(1, 3))
        val wrongHeadModelSha = sha256(wrongHeadBytes)
        val semanticClassesV3 = semanticClassesV2
            .replace("\"model_version\": \"8\"", "\"model_version\": \"9\"")
        val classesShaV3 = classesSha256(semanticClassesV3)
        val bundleShaV3 = bundleSha256(wrongHeadModelSha, classesShaV3)
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    manifestBody(
                        version = "9",
                        modelSha = wrongHeadModelSha,
                        classesSha = classesShaV3,
                        bundleSha = bundleShaV3,
                        semanticClasses = semanticClassesV3,
                        sizeBytes = wrongHeadBytes.size,
                    ),
                ),
        )
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(wrongHeadBytes)),
        )

        val wrongHeadUpdate = runBlocking { repo.syncAquaModel(context) }

        assertThat(wrongHeadUpdate.getOrNull()).isFalse()
        assertThat(AquaModelManager.isUpToDate(context, bundleShaV2)).isTrue()
        assertThat(AquaModelManager.isUpToDate(context, bundleShaV3)).isFalse()
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/model")

        // A transient server failure preserves the last-known-good pointer.
        server.enqueue(MockResponse().setResponseCode(500))
        val transientFailure = runBlocking { repo.syncAquaModel(context) }
        assertThat(transientFailure.getOrNull()).isFalse()
        assertThat(AquaModelManager.isUpToDate(context, bundleShaV2)).isTrue()
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")

        // A successful available:false response is authoritative revocation:
        // deactivate the pointer but retain immutable bytes for rollback.
        val retainedModel = AquaModelManager.modelFile(context)
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody("""{"available":false}"""),
        )
        val withdrawn = runBlocking { repo.syncAquaModel(context) }
        assertThat(withdrawn.getOrNull()).isFalse()
        assertThat(AquaModelManager.isInstalled(context)).isFalse()
        assertThat(retainedModel.isFile).isTrue()
        assertThat(server.takeRequest().path).isEqualTo("/api/aqua/manifest")
    }

    @Test
    fun syncAquaModel_rejectsDigestValidInt8InputBeforeActivation() {
        val modelBytes = tfliteContractBytes(inputType = TensorType.INT8)
        val modelSha = sha256(modelBytes)
        val semanticClasses = """
            {
              "model_version": "10",
              "model_family": "aqua",
              "class_names": ["healthy", "leaf_spot"],
              "training": {"img_size": 224, "eval_resize_ratio": 1.05},
              "inference": {
                "layout": "NHWC", "tta": "none", "output_semantics": "logits",
                "normalize_mean": [0.485, 0.456, 0.406],
                "normalize_std": [0.229, 0.224, 0.225]
              }
            }
        """.trimIndent()
        val classesSha = classesSha256(semanticClasses)
        val bundleSha = bundleSha256(modelSha, classesSha)
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/json")
                .setBody(
                    manifestBody(
                        version = "10",
                        modelSha = modelSha,
                        classesSha = classesSha,
                        bundleSha = bundleSha,
                        semanticClasses = semanticClasses,
                        sizeBytes = modelBytes.size,
                    ),
                ),
        )
        server.enqueue(
            MockResponse().setResponseCode(200)
                .setHeader("Content-Type", "application/octet-stream")
                .setBody(Buffer().write(modelBytes)),
        )

        val result = runBlocking { repo.syncAquaModel(context) }

        assertThat(result.getOrNull()).isFalse()
        assertThat(AquaModelManager.isInstalled(context)).isFalse()
    }

    private fun canonicalJson(element: JsonElement): String = when {
        element.isJsonNull -> "null"
        element.isJsonArray -> element.asJsonArray.joinToString(",", "[", "]") {
            canonicalJson(it)
        }
        element.isJsonObject -> element.asJsonObject.entrySet()
            .sortedBy { it.key }
            .joinToString(",", "{", "}") { entry ->
                "${JsonPrimitive(entry.key)}:${canonicalJson(entry.value)}"
            }
        else -> element.toString()
    }

    private fun hexBytes(value: String): ByteArray = ByteArray(value.length / 2) { index ->
        value.substring(index * 2, index * 2 + 2).toInt(16).toByte()
    }

    private fun sha256(bytes: ByteArray): String = MessageDigest.getInstance("SHA-256")
        .digest(bytes)
        .joinToString("") { "%02x".format(it) }

    private fun classesSha256(semanticClasses: String): String =
        sha256(canonicalJson(JsonParser.parseString(semanticClasses)).toByteArray(Charsets.UTF_8))

    private fun bundleSha256(modelSha: String, classesSha: String): String =
        MessageDigest.getInstance("SHA-256").apply {
            update("plantvision-aqua-bundle-v1\u0000".toByteArray(Charsets.UTF_8))
            update(hexBytes(modelSha))
            update(hexBytes(classesSha))
        }.digest().joinToString("") { "%02x".format(it) }

    private fun manifestBody(
        version: String,
        modelSha: String,
        classesSha: String,
        bundleSha: String,
        semanticClasses: String,
        sizeBytes: Int,
    ): String = """
        {
          "available": true,
          "version": "$version",
          "sha256": "$modelSha",
          "classes_sha256": "$classesSha",
          "bundle_sha256": "$bundleSha",
          "bundle_schema_version": 1,
          "size_bytes": $sizeBytes,
          "classes": $semanticClasses
        }
    """.trimIndent()

    /** Minimal structural TFLite FlatBuffer; graph metadata only, never run. */
    private fun tfliteContractBytes(
        inputType: Byte = TensorType.FLOAT32,
        outputType: Byte = TensorType.FLOAT32,
        inputShapeValues: IntArray = intArrayOf(1, 224, 224, 3),
        outputShape: IntArray = intArrayOf(1, 2),
    ): ByteArray {
        val builder = FlatBufferBuilder(512)
        val inputName = builder.createString("input")
        val inputShape = Tensor.createShapeVector(builder, inputShapeValues)
        val inputTensor = Tensor.createTensor(
            builder,
            inputShape,
            inputType,
            0L,
            inputName,
            0,
            false,
            0,
            0,
        )
        val outputName = builder.createString("logits")
        val outputShapeVector = Tensor.createShapeVector(builder, outputShape)
        val outputTensor = Tensor.createTensor(
            builder,
            outputShapeVector,
            outputType,
            0L,
            outputName,
            0,
            false,
            0,
            0,
        )
        val tensors = SubGraph.createTensorsVector(
            builder,
            intArrayOf(inputTensor, outputTensor),
        )
        val inputs = SubGraph.createInputsVector(builder, intArrayOf(0))
        val outputs = SubGraph.createOutputsVector(builder, intArrayOf(1))
        val subgraphName = builder.createString("main")
        val subgraph = SubGraph.createSubGraph(
            builder,
            tensors,
            inputs,
            outputs,
            0,
            subgraphName,
        )
        val subgraphs = Model.createSubgraphsVector(builder, intArrayOf(subgraph))
        val emptyBuffer = TfliteBuffer.createBuffer(builder, 0)
        val buffers = Model.createBuffersVector(builder, intArrayOf(emptyBuffer))
        val description = builder.createString("Aqua tensor-contract fixture")
        val model = Model.createModel(
            builder,
            3L,
            0,
            subgraphs,
            description,
            buffers,
            0,
            0,
            0,
        )
        Model.finishModelBuffer(builder, model)
        return builder.sizedByteArray()
    }

    private fun clearInstalledAqua() {
        context.getSharedPreferences("plantdiseases_aqua", Context.MODE_PRIVATE)
            .edit()
            .clear()
            .commit()
        File(context.filesDir, "aqua").deleteRecursively()
    }
